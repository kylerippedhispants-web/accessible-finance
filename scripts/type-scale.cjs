'use strict';

// Shared roles for page CSS and generated guide artwork. SVG values are pixels;
// the stylesheet converts them to rem so browser text-size preferences work.
const type = { caption: 14, control: 14, compact: 16, body: 18, lead: 20, subheading: 28, section: 40, title: 64, value: 32 };
const space = [4, 8, 12, 16, 20, 24, 32, 48, 64, 96];
const spacing = Object.fromEntries(space.map((size) => [size, size]));
const line = { body: 1.75, compact: 1.6, label: 1.5, heading: 1.15, title: 1.08, value: 1.2 };

function createTypeStylesheet() {
  const declarations = [
    ...Object.entries(type).map(([role, size]) => `  --type-${role}: ${size / 16}rem;`),
    ...space.map((size) => `  --space-${size}: ${size / 16}rem;`),
    ...Object.entries(line).map(([role, value]) => `  --line-${role}: ${value};`),
    '  --card-padding: var(--space-24);',
    '  --section-space: var(--space-64);',
    '  --page-gutter: var(--space-24);',
  ].join('\n');
  return `/* Generated by scripts/type-scale.cjs; edit the shared scale there. */\n:root {\n${declarations}\n}\n@media (max-width: 768px) {\n  :root { --type-title: 3rem; --type-section: 2.25rem; }\n}\n@media (max-width: 600px) {\n  :root {\n    --type-title: 2.5rem; --type-section: 2rem; --type-subheading: 1.5rem;\n    --type-body: 1.0625rem; --type-lead: 1.125rem;\n    --card-padding: var(--space-20); --section-space: var(--space-48); --page-gutter: var(--space-20);\n  }\n}\n`;
}

module.exports = { type, space, spacing, line, createTypeStylesheet };
